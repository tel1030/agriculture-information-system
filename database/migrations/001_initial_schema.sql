CREATE FUNCTION public.check_harvest_date () RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE planting_day DATE;
BEGIN
    SELECT planting_date INTO planting_day FROM public.plantings WHERE planting_id = NEW.planting_id FOR SHARE;
    IF planting_day IS NULL OR NEW.harvest_date < planting_day THEN
        RAISE EXCEPTION 'Harvest date cannot be before the planting date';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_harvest_date
BEFORE INSERT OR UPDATE ON public.harvests FOR EACH ROW
EXECUTE FUNCTION public.check_harvest_date ();

CREATE FUNCTION public.check_planting_date_change () RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.planting_date > OLD.planting_date AND EXISTS (
        SELECT 1 FROM public.harvests
        WHERE planting_id = OLD.planting_id AND harvest_date < NEW.planting_date
    ) THEN
        RAISE EXCEPTION 'Planting date cannot be moved after a recorded harvest';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_planting_date_change
BEFORE UPDATE OF planting_date ON public.plantings FOR EACH ROW
EXECUTE FUNCTION public.check_planting_date_change ();

