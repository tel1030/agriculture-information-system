CREATE FUNCTION public.touch_updated_at () RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_app_users_updated
BEFORE UPDATE ON public.app_users FOR EACH ROW
