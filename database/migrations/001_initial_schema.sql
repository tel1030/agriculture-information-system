-- Agriculture Information System: exactly 13 purpose-built tables.
-- Beginner Note: Run this migration once in a new Supabase development project.
CREATE TABLE public.crop_options (
    option_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_type VARCHAR(20) NOT NULL CHECK (option_type IN ('category', 'season')),
    option_label VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (option_type, option_label),
    UNIQUE (option_id, option_type)
);

CREATE TABLE public.soil_types (
    soil_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soil_type_name VARCHAR(50) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE public.irrigation_types (
    irrigation_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    irrigation_type_name VARCHAR(50) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE public.planting_statuses (
    status_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(30) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE public.harvest_options (
    option_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_type VARCHAR(20) NOT NULL CHECK (option_type IN ('grade', 'remark')),
    option_label VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (option_type, option_label),
    UNIQUE (option_id, option_type)
);

CREATE TABLE public.app_users (
    user_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL CHECK (length(trim(full_name)) > 0),
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('Administrator', 'Staff')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    failed_login_count INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    locked_until TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_app_users_email_lower ON public.app_users (lower(email));

CREATE TABLE public.user_preferences (
    user_id BIGINT PRIMARY KEY REFERENCES public.app_users (user_id) ON DELETE CASCADE,
    theme VARCHAR(10) NOT NULL DEFAULT 'light' CHECK (theme IN ('light', 'dark')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.farmers (
    farmer_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL CHECK (length(trim(first_name)) > 0),
    last_name VARCHAR(50) NOT NULL CHECK (length(trim(last_name)) > 0),
    contact_number VARCHAR(20),
    address VARCHAR(150) NOT NULL CHECK (length(trim(address)) > 0),
    date_registered DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        contact_number IS NULL
        OR contact_number !~ '[[:cntrl:]]'
    )
);

CREATE TABLE public.farms (
    farm_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES public.farmers (farmer_id) ON DELETE RESTRICT,
    farm_name VARCHAR(100) NOT NULL CHECK (length(trim(farm_name)) > 0),
    location VARCHAR(150) NOT NULL CHECK (length(trim(location)) > 0),
    area_hectares NUMERIC(8, 2) NOT NULL CHECK (area_hectares > 0),
    soil_type_id SMALLINT NOT NULL REFERENCES public.soil_types (soil_type_id) ON DELETE RESTRICT,
    irrigation_type_id SMALLINT NOT NULL REFERENCES public.irrigation_types (irrigation_type_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (farmer_id, farm_name)
);

CREATE TABLE public.crops (
    crop_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    crop_name VARCHAR(80) NOT NULL CHECK (length(trim(crop_name)) > 0),
    variety VARCHAR(80) NOT NULL CHECK (length(trim(variety)) > 0),
    category_option_id SMALLINT NOT NULL,
    category_option_type VARCHAR(20) NOT NULL DEFAULT 'category' CHECK (category_option_type = 'category'),
    growing_period_days INTEGER NOT NULL CHECK (growing_period_days >= 1),
    season_option_id SMALLINT NOT NULL,
    season_option_type VARCHAR(20) NOT NULL DEFAULT 'season' CHECK (season_option_type = 'season'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (category_option_id, category_option_type) REFERENCES public.crop_options (option_id, option_type) ON DELETE RESTRICT,
    FOREIGN KEY (season_option_id, season_option_type) REFERENCES public.crop_options (option_id, option_type) ON DELETE RESTRICT,
    UNIQUE (crop_name, variety)
);

-- [LEARNING EXPLANATION] Each crop option foreign key includes its type. PostgreSQL therefore rejects a season ID in the category field (and vice versa).
CREATE TABLE public.plantings (
    planting_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    farm_id BIGINT NOT NULL REFERENCES public.farms (farm_id) ON DELETE RESTRICT,
    crop_id BIGINT NOT NULL REFERENCES public.crops (crop_id) ON DELETE RESTRICT,
    planting_date DATE NOT NULL,
    area_planted NUMERIC(8, 2) NOT NULL CHECK (area_planted > 0),
    seed_quantity NUMERIC(8, 2) NOT NULL CHECK (seed_quantity >= 0),
    expected_harvest_date DATE NOT NULL,
    status_id SMALLINT NOT NULL REFERENCES public.planting_statuses (status_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (expected_harvest_date >= planting_date)
);

CREATE TABLE public.harvests (
    harvest_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    planting_id BIGINT NOT NULL REFERENCES public.plantings (planting_id) ON DELETE RESTRICT,
    harvest_date DATE NOT NULL,
    quantity_kg NUMERIC(10, 2) NOT NULL CHECK (quantity_kg > 0),
    selling_price_per_kg NUMERIC(10, 2) CHECK (selling_price_per_kg >= 0),
    quality_option_id SMALLINT NOT NULL,
    quality_option_type VARCHAR(20) NOT NULL DEFAULT 'grade' CHECK (quality_option_type = 'grade'),
    remark_option_id SMALLINT NOT NULL,
    remark_option_type VARCHAR(20) NOT NULL DEFAULT 'remark' CHECK (remark_option_type = 'remark'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (quality_option_id, quality_option_type) REFERENCES public.harvest_options (option_id, option_type) ON DELETE RESTRICT,
    FOREIGN KEY (remark_option_id, remark_option_type) REFERENCES public.harvest_options (option_id, option_type) ON DELETE RESTRICT
);

-- [LEARNING EXPLANATION] The harvest option type in each composite foreign key keeps grade choices separate from the instructor's remark IDs.
CREATE TABLE public.audit_logs (
    log_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES public.app_users (user_id) ON DELETE SET NULL,
    action VARCHAR(20) NOT NULL CHECK (
        action IN (
            'INSERT',
            'UPDATE',
            'DELETE',
            'LOGIN',
            'LOGOUT',
            'LOGIN_FAILED',
            'PASSWORD_CHANGE',
            'ACCOUNT_CHANGE'
        )
    ),
    entity_table VARCHAR(63) NOT NULL,
    record_pk TEXT,
    old_values JSONB,
    new_values JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

